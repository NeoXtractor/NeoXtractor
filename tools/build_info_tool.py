"""A tool script for managing build information."""

import datetime
import os
import subprocess
import sys
import json
import tomllib

project_dir = os.path.realpath(os.path.join(os.path.dirname(__file__), ".."))

if __name__ != "__main__":
    raise ImportError("This script is not meant to be imported.")

def _version_from_pyproject():
    """Read the project version from pyproject.toml, or None if unavailable."""
    path = os.path.join(project_dir, "pyproject.toml")
    try:
        with open(path, "rb") as file:
            data = tomllib.load(file)
    except (OSError, tomllib.TOMLDecodeError):
        return None
    version = data.get("project", {}).get("version")
    return version if isinstance(version, str) else None

def _generate():
    try:
        # Get current commit hash
        commit_hash = subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            stderr=subprocess.DEVNULL
        ).decode("utf-8").strip()

        # Get current branch
        branch = subprocess.check_output(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            stderr=subprocess.DEVNULL
        ).decode("utf-8").strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        commit_hash = "unknown"
        branch = "unknown"

    version = None
    try:
        # This gets tags that point to the current commit
        tag = subprocess.check_output(
            ["git", "describe", "--exact-match", "--tags", "HEAD"],
            stderr=subprocess.DEVNULL
        ).decode("utf-8").strip()

        if tag.startswith("v"):
            version = tag[1:]
        else:
            print("Tag does not look like a version.")
    except subprocess.CalledProcessError:
        print("No tag found for the current commit.")

    if version is None:
        # Fall back to the declared project version
        version = _version_from_pyproject()
        if version is not None:
            print(f"Using version {version} from pyproject.toml.")

    if version is None:
        print("No version found.")

    time = datetime.datetime.now().timestamp()

    with open(os.path.join(project_dir, "build", "_build_info.py"), "w", encoding="utf-8") as file:
        file.write(
        """# This file is auto-generated by build_info_tool.py
# Do not edit this file manually.
# It contains build information for the application.

BUILD_INFO = """)
        file.write(json.dumps({
            "version": version,
            "build_time": time,
            "commit_hash": commit_hash,
            "branch": branch
        }, indent=2).replace("null", "None"))

cmd = sys.argv[1] if len(sys.argv) > 1 else ""

if cmd == "gen":
    _generate()
elif cmd == "del":
    os.remove(os.path.join(project_dir, "build", "_build_info.py"))
else:
    print("Invalid command. Use 'gen' to generate build info or 'del' to delete it.")
